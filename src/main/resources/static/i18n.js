let lang = localStorage.getItem("lang");
if (!LANGS[lang]) lang = "en";

function t(key, params = {}) {
  const s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ""));
}

// Sets language, direction, and fills every [data-i18n] element.
function applyLang(code) {
  if (!LANGS[code]) code = "en";
  lang = code;
  localStorage.setItem("lang", code);
  document.documentElement.lang = code;
  document.documentElement.dir = LANGS[code].dir;
  applyTranslations();
}

function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
      el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-label]").forEach(el => {
    el.label = t(el.dataset.i18nLabel);   // <optgroup label>
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
}


// Fills a <select id="lang-select"> from LANGS and wires it up.
function initLangSelect(selectId = "lang-select") {
  const sel = document.getElementById(selectId);
  if (!sel) return;
  sel.innerHTML = "";
  Object.entries(LANGS).forEach(([code, cfg]) => {
    const opt = document.createElement("option");
    opt.value = code;
    opt.textContent = cfg.label;
    if (code === lang) opt.selected = true;
    sel.appendChild(opt);
  });
 sel.addEventListener("change", () => { applyLang(sel.value); location.reload(); });
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(lang);
  initLangSelect();
});

